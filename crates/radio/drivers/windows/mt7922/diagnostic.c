C_ASSERT(sizeof(AWDROP_DIAG_RESET_INFO) == 16);
C_ASSERT(sizeof(aw_dma_descriptor) == AW_DESC_SIZE);

NTSTATUS DriverEntry(PDRIVER_OBJECT driver, PUNICODE_STRING registry) {
    WDF_DRIVER_CONFIG config;
    WDF_DRIVER_CONFIG_INIT(&config, AwDeviceAdd);
    return WdfDriverCreate(driver, registry, WDF_NO_OBJECT_ATTRIBUTES, &config, WDF_NO_HANDLE);
}

NTSTATUS AwDeviceAdd(WDFDRIVER driver, PWDFDEVICE_INIT init) {
    WDF_PNPPOWER_EVENT_CALLBACKS callbacks;
    WDF_OBJECT_ATTRIBUTES attributes;
    WDF_IO_QUEUE_CONFIG queue;
    WDFDEVICE device;
    UNICODE_STRING sddl;
    NTSTATUS status;
    UNREFERENCED_PARAMETER(driver);

    RtlInitUnicodeString(&sddl, L"D:P(A;;GA;;;SY)(A;;GA;;;BA)");
    WdfDeviceInitSetDeviceType(init, FILE_DEVICE_UNKNOWN);
    WdfDeviceInitSetCharacteristics(init, FILE_DEVICE_SECURE_OPEN | FILE_AUTOGENERATED_DEVICE_NAME, TRUE);
    WdfDeviceInitSetIoType(init, WdfDeviceIoBuffered);
    status = WdfDeviceInitAssignSDDLString(init, &sddl);
    if (!NT_SUCCESS(status)) return status;
    WDF_PNPPOWER_EVENT_CALLBACKS_INIT(&callbacks);
    callbacks.EvtDevicePrepareHardware = AwPrepare;
    callbacks.EvtDeviceReleaseHardware = AwRelease;
    callbacks.EvtDeviceSurpriseRemoval = AwSurpriseRemoval;
    WdfDeviceInitSetPnpPowerEventCallbacks(init, &callbacks);

    WDF_OBJECT_ATTRIBUTES_INIT_CONTEXT_TYPE(&attributes, AWDROP_DIAG_DEVICE);
    attributes.ExecutionLevel = WdfExecutionLevelPassive;
    attributes.SynchronizationScope = WdfSynchronizationScopeDevice;
    status = WdfDeviceCreate(&init, &attributes, &device);
    if (!NT_SUCCESS(status)) return status;
    status = WdfDeviceCreateDeviceInterface(device, &GUID_DEVINTERFACE_AWDROP_MT7922_DIAGNOSTIC, NULL);
    if (!NT_SUCCESS(status)) return status;
    WDF_IO_QUEUE_CONFIG_INIT_DEFAULT_QUEUE(&queue, WdfIoQueueDispatchSequential);
    queue.PowerManaged = WdfTrue;
    queue.EvtIoDeviceControl = AwControl;
    return WdfIoQueueCreate(device, &queue, WDF_NO_OBJECT_ATTRIBUTES, WDF_NO_HANDLE);
}

VOID AwSurpriseRemoval(WDFDEVICE device) {
    AWDROP_DIAG_DEVICE *ctx = AwGetDevice(device);
    /* Surprise removal is not serialized with queue callbacks by WDF. The
     * mapping is released by AwRelease after the framework drains the queue. */
    InterlockedExchange(&ctx->surprise_removed, 1);
}

static int AwOwnRead(void *context, uint32_t *value) {
    AWDROP_DIAG_DEVICE *ctx = (AWDROP_DIAG_DEVICE *)context;
    if (InterlockedCompareExchange(&ctx->surprise_removed, 0, 0) ||
        !ctx->bar0_mapping || ctx->bar0_mapping_length < AW_LPCTL_BAR_OFFSET + sizeof(ULONG)) return 0;
    *value = READ_REGISTER_ULONG((volatile ULONG *)((PUCHAR)ctx->bar0_mapping + AW_LPCTL_BAR_OFFSET));
    return 1;
}

static int AwOwnWrite(void *context, uint32_t value) {
    AWDROP_DIAG_DEVICE *ctx = (AWDROP_DIAG_DEVICE *)context;
    if (InterlockedCompareExchange(&ctx->surprise_removed, 0, 0) ||
        !ctx->bar0_mapping || ctx->bar0_mapping_length < AW_LPCTL_BAR_OFFSET + sizeof(ULONG) ||
        (value != AW_LPCTL_SET_FW_OWN && value != AW_LPCTL_CLEAR_FW_OWN)) return 0;
    WRITE_REGISTER_ULONG((volatile ULONG *)((PUCHAR)ctx->bar0_mapping + AW_LPCTL_BAR_OFFSET), value);
    return 1;
}

static int AwOwnDelay(void *context, uint32_t ms) {
    AWDROP_DIAG_DEVICE *ctx = (AWDROP_DIAG_DEVICE *)context;
    LARGE_INTEGER interval;
    if (InterlockedCompareExchange(&ctx->surprise_removed, 0, 0)) return 0;
    interval.QuadPart = -((LONGLONG)ms * 10000);
    return NT_SUCCESS(KeDelayExecutionThread(KernelMode, FALSE, &interval));
}

static int AwOwnInspectDma(void *context, uint32_t *flags) {
    AWDROP_DIAG_DEVICE *ctx = (AWDROP_DIAG_DEVICE *)context;
    const SIZE_T offset = 0xd4208u; /* MT7922 WFDMA0 global configuration. */
    if (InterlockedCompareExchange(&ctx->surprise_removed, 0, 0) || !ctx->bar0_mapping ||
        ctx->bar0_mapping_length < offset + sizeof(ULONG)) return 0;
    *flags = READ_REGISTER_ULONG((volatile ULONG *)((PUCHAR)ctx->bar0_mapping + offset));
    return 1;
}

typedef struct AW_WDF_ALLOCATOR { WDFDMAENABLER enabler; NTSTATUS last_status; } AW_WDF_ALLOCATOR;
static int AwAllocateMcuBuffer(void *context, uint32_t bytes, aw_mcu_block *out) {
    AW_WDF_ALLOCATOR *allocator = (AW_WDF_ALLOCATOR *)context;
    WDFCOMMONBUFFER buffer = NULL;
    PHYSICAL_ADDRESS logical;
    allocator->last_status = WdfCommonBufferCreate(allocator->enabler, bytes, WDF_NO_OBJECT_ATTRIBUTES, &buffer);
    if (!NT_SUCCESS(allocator->last_status)) return 0;
    out->handle = buffer;
    out->virtual_address = WdfCommonBufferGetAlignedVirtualAddress(buffer);
    logical = WdfCommonBufferGetAlignedLogicalAddress(buffer);
    out->address = (uint64_t)logical.QuadPart;
    out->bytes = bytes;
    if (out->virtual_address) RtlZeroMemory(out->virtual_address, bytes);
    return 1;
}
static void AwFreeMcuBuffer(void *context, void *handle) {
    UNREFERENCED_PARAMETER(context);
    WdfObjectDelete((WDFCOMMONBUFFER)handle);
}

NTSTATUS AwPrepare(WDFDEVICE device, WDFCMRESLIST raw, WDFCMRESLIST translated) {
    AWDROP_DIAG_DEVICE *ctx = AwGetDevice(device);
    BUS_INTERFACE_STANDARD bus;
    DEVICE_RESET_INTERFACE_STANDARD reset;
    PCI_COMMON_CONFIG pci;
    NTSTATUS status;
    ULONG bytes, index, count;
    uint64_t bar0 = 0;
    PHYSICAL_ADDRESS translated_bar0 = {0};
    const SIZE_T aperture_size = 0x100000u;
    if (ctx->prepared || ctx->bar0_mapping) return STATUS_INVALID_DEVICE_STATE;
    ctx->prepared = FALSE;
    ctx->bar0_mapping = NULL;
    ctx->bar0_mapping_length = 0;
    RtlZeroMemory(&ctx->info, sizeof(ctx->info));
    RtlZeroMemory(&ctx->reset_info, sizeof(ctx->reset_info));
    RtlZeroMemory(&bus, sizeof(bus));
    RtlZeroMemory(&pci, sizeof(pci));
    status = WdfFdoQueryForInterface(device, &GUID_BUS_INTERFACE_STANDARD,
        (PINTERFACE)&bus, sizeof(bus), 1, NULL);
    if (!NT_SUCCESS(status)) return status;
    if (!bus.InterfaceDereference) return STATUS_INVALID_DEVICE_STATE;
    if (!bus.GetBusData) {
        bus.InterfaceDereference(bus.Context);
        return STATUS_INVALID_DEVICE_STATE;
    }
    bytes = bus.GetBusData(bus.Context, PCI_WHICHSPACE_CONFIG, &pci, 0, PCI_COMMON_HDR_LENGTH);
    bus.InterfaceDereference(bus.Context);
    if (bytes != PCI_COMMON_HDR_LENGTH) return STATUS_DEVICE_DATA_ERROR;
    if ((pci.HeaderType & 0x7f) != PCI_DEVICE_TYPE ||
        !((pci.VendorID == 0x14c3 && (pci.DeviceID == 0x0616 || pci.DeviceID == 0x7922)) ||
          (pci.VendorID == 0x0b48 && pci.DeviceID == 0x7922))) return STATUS_NOT_SUPPORTED;
    ctx->info.size = sizeof(ctx->info);
    ctx->info.version = AWDROP_DIAG_VERSION;
    ctx->info.vendor = pci.VendorID;
    ctx->info.device = pci.DeviceID;
    ctx->info.subsystem_vendor = pci.u.type0.SubVendorID;
    ctx->info.subsystem_device = pci.u.type0.SubSystemID;
    ctx->info.revision = pci.RevisionID;
    ctx->info.radio_ready = 0;
    /* Read bus-provided reset capability only; never request a reset. */
    ctx->reset_info.size = sizeof(ctx->reset_info);
    ctx->reset_info.version = 1;
    RtlZeroMemory(&reset, sizeof(reset));
    reset.Size = sizeof(reset);
    reset.Version = DEVICE_RESET_INTERFACE_VERSION_1;
    status = WdfFdoQueryForInterface(device, &GUID_DEVICE_RESET_INTERFACE_STANDARD,
        (PINTERFACE)&reset, sizeof(reset), DEVICE_RESET_INTERFACE_VERSION_1, NULL);
    if (NT_SUCCESS(status)) {
        if (!reset.InterfaceDereference) return STATUS_INVALID_DEVICE_STATE;
        if (reset.DeviceReset) {
            ctx->reset_info.queried = 1;
            ctx->reset_info.supported_types = reset.SupportedResetTypes & 3u;
        }
        reset.InterfaceDereference(reset.Context);
    }
    /* Match the PCI BAR to its paired raw and translated PnP resources. */
    count = WdfCmResourceListGetCount(raw);
    if (count != WdfCmResourceListGetCount(translated)) return STATUS_DEVICE_CONFIGURATION_ERROR;
    (void)aw_bar0_address(pci.u.type0.BaseAddresses[0], pci.u.type0.BaseAddresses[1], &bar0);
    for (index = 0; index < count; ++index) {
        PCM_PARTIAL_RESOURCE_DESCRIPTOR source = WdfCmResourceListGetDescriptor(raw, index);
        PCM_PARTIAL_RESOURCE_DESCRIPTOR target = WdfCmResourceListGetDescriptor(translated, index);
        if (!source || !target) return STATUS_DEVICE_CONFIGURATION_ERROR;
        if (target->Type == CmResourceTypeInterrupt) ++ctx->info.interrupt_resources;
        if (source->Type != CmResourceTypeMemory || target->Type != CmResourceTypeMemory) continue;
        ++ctx->info.memory_resources;
        if (aw_bar0_resource_matches(bar0, (uint64_t)source->u.Memory.Start.QuadPart,
                                    source->u.Memory.Length, target->u.Memory.Length)) {
            ++ctx->info.bar0_matches;
            ctx->info.bar0_bytes = target->u.Memory.Length;
            translated_bar0 = target->u.Memory.Start;
        }
    }
    /* Ambiguous mappings are not safe for a later hardware implementation. */
    if (ctx->info.bar0_matches != 1) ctx->info.bar0_bytes = 0;
    /* The MT7921 PCI register map uses the first MiB. Mapping establishes the
     * PnP lifetime only: no reads or writes are performed in this prototype. */
    if (ctx->info.bar0_bytes >= aperture_size) {
        ctx->bar0_mapping = MmMapIoSpace(translated_bar0, aperture_size, MmNonCached);
        if (!ctx->bar0_mapping) return STATUS_INSUFFICIENT_RESOURCES;
        ctx->bar0_mapping_length = aperture_size;
    }
    ctx->prepared = TRUE;
    return STATUS_SUCCESS;
}

NTSTATUS AwRelease(WDFDEVICE device, WDFCMRESLIST translated) {
    AWDROP_DIAG_DEVICE *ctx = AwGetDevice(device);
    UNREFERENCED_PARAMETER(translated);
    ctx->prepared = FALSE;
    if (ctx->bar0_mapping) {
        MmUnmapIoSpace(ctx->bar0_mapping, ctx->bar0_mapping_length);
        ctx->bar0_mapping = NULL;
        ctx->bar0_mapping_length = 0;
    }
    RtlZeroMemory(&ctx->info, sizeof(ctx->info));
    RtlZeroMemory(&ctx->reset_info, sizeof(ctx->reset_info));
    return STATUS_SUCCESS;
}

VOID AwControl(WDFQUEUE queue, WDFREQUEST request, size_t output_length,
               size_t input_length, ULONG code) {
    AWDROP_DIAG_DEVICE *ctx = AwGetDevice(WdfIoQueueGetDevice(queue));
    AWDROP_DIAG_INFO *output;
    size_t actual;
    NTSTATUS status;
    UNREFERENCED_PARAMETER(input_length);
    if (code != IOCTL_AWDROP_MT7922_GET_INFO && code != IOCTL_AWDROP_MT7922_DMA_TEST &&
        code != IOCTL_AWDROP_MT7922_OWN_TEST && code != IOCTL_AWDROP_MT7922_RESET_INFO) {
        WdfRequestComplete(request, STATUS_INVALID_DEVICE_REQUEST);
        return;
    }
    if (!ctx->prepared) {
        WdfRequestComplete(request, STATUS_DEVICE_NOT_READY);
        return;
    }
    if (code == IOCTL_AWDROP_MT7922_RESET_INFO) {
        AWDROP_DIAG_RESET_INFO *result;
        if (output_length < sizeof(*result)) { WdfRequestComplete(request, STATUS_BUFFER_TOO_SMALL); return; }
        status = WdfRequestRetrieveOutputBuffer(request, sizeof(*result), (PVOID *)&result, &actual);
        if (!NT_SUCCESS(status)) { WdfRequestComplete(request, status); return; }
        *result = ctx->reset_info;
        WdfRequestCompleteWithInformation(request, STATUS_SUCCESS, sizeof(*result));
        return;
    }
    if (code == IOCTL_AWDROP_MT7922_OWN_TEST) {
        WDFDEVICE device = WdfIoQueueGetDevice(queue);
        AWDROP_DIAG_OWN_INFO *result;
        aw_own_io io = {ctx, AwOwnRead, AwOwnWrite, AwOwnDelay, AwOwnInspectDma};
        aw_own_result outcome;
        uint32_t dma_flags;
        int dma_valid;
        if (input_length != 0) { WdfRequestComplete(request, STATUS_INVALID_PARAMETER); return; }
        if (ctx->ownership_unsafe || !ctx->bar0_mapping ||
            InterlockedCompareExchange(&ctx->surprise_removed, 0, 0)) {
            WdfRequestComplete(request, STATUS_DEVICE_NOT_READY);
            return;
        }
        if (output_length < sizeof(*result)) { WdfRequestComplete(request, STATUS_BUFFER_TOO_SMALL); return; }
        status = WdfRequestRetrieveOutputBuffer(request, sizeof(*result), (PVOID *)&result, &actual);
        if (!NT_SUCCESS(status)) { WdfRequestComplete(request, status); return; }
        outcome = aw_own_roundtrip(&io, &dma_flags, &dma_valid);
        if (outcome == AW_OWN_RECOVERY_FAILED) ctx->ownership_unsafe = TRUE;
        result->size = sizeof(*result);
        result->version = 2;
        result->result = (ULONG)outcome;
        result->dma_valid = (ULONG)dma_valid;
        result->dma_flags = dma_flags;
        WdfRequestCompleteWithInformation(request, STATUS_SUCCESS, sizeof(*result));
        /* An unconfirmed handoff is not a usable device. Ask PnP to stop it;
         * this does not claim that the firmware or vendor driver recovered. */
        if (outcome == AW_OWN_RECOVERY_FAILED && !InterlockedCompareExchange(&ctx->surprise_removed, 0, 0))
            WdfDeviceSetFailed(device, WdfDeviceFailedNoRestart);
        return;
    }
    if (code == IOCTL_AWDROP_MT7922_DMA_TEST) {
        WDFDEVICE device = WdfIoQueueGetDevice(queue);
        WDF_DMA_ENABLER_CONFIG config;
        WDFDMAENABLER enabler = NULL;
        AW_WDF_ALLOCATOR wdf_allocator = {NULL, STATUS_SUCCESS};
        aw_mcu_allocator allocator = {&wdf_allocator, AwAllocateMcuBuffer, AwFreeMcuBuffer};
        aw_mcu_memory memory = {0};
        AWDROP_DIAG_DMA_INFO *result;
        if (!ctx->info.bar0_bytes) { WdfRequestComplete(request, STATUS_DEVICE_CONFIGURATION_ERROR); return; }
        if (output_length < sizeof(*result)) { WdfRequestComplete(request, STATUS_BUFFER_TOO_SMALL); return; }
        status = WdfRequestRetrieveOutputBuffer(request, sizeof(*result), (PVOID *)&result, &actual);
        if (!NT_SUCCESS(status)) { WdfRequestComplete(request, status); return; }
        /* Preserve any stricter alignment already imposed by the bus. */
        {
            ULONG alignment = WdfDeviceGetAlignmentRequirement(device);
            WdfDeviceSetAlignmentRequirement(device, alignment < 15u ? 15u : alignment);
        }
        WDF_DMA_ENABLER_CONFIG_INIT(&config, WdfDmaProfileScatterGather, AW_EVENT_PAYLOAD_BYTES);
        status = WdfDmaEnablerCreate(device, &config, WDF_NO_OBJECT_ATTRIBUTES, &enabler);
        if (!NT_SUCCESS(status)) { WdfRequestComplete(request, status); return; }
        wdf_allocator.enabler = enabler;
        if (!aw_mcu_memory_prepare(&memory, &allocator))
            status = NT_SUCCESS(wdf_allocator.last_status) ? STATUS_CONFLICTING_ADDRESSES : wdf_allocator.last_status;
        if (NT_SUCCESS(status) && !aw_ring_initialize((aw_dma_descriptor *)memory.blocks[0].virtual_address,
                (aw_dma_descriptor *)memory.blocks[1].virtual_address,
                (aw_dma_descriptor *)memory.blocks[2].virtual_address, memory.blocks[3].address))
            status = STATUS_INVALID_DEVICE_STATE;
        if (NT_SUCCESS(status)) {
            aw_tx_queue check;
            aw_event_queue events;
            aw_dma_descriptor *event_descriptors = (aw_dma_descriptor *)memory.blocks[2].virtual_address;
            uint32_t index;
            uint32_t buffer, length;
            /* Exercise queue bookkeeping in private memory only. The fake
             * completion index is never read from or sent to hardware. */
            if (!aw_tx_queue_init(&check, (aw_dma_descriptor *)memory.blocks[0].virtual_address, AW_MCU_TX_COUNT) ||
                !aw_tx_queue_submit(&check, memory.blocks[4].address, AW_MCU_PACKET_BYTES, &index) || index != 0 ||
                aw_tx_queue_reclaim(&check, 1, &index) != 1 || index != 0 || check.queued != 0)
                status = STATUS_DATA_ERROR;
            if (NT_SUCCESS(status)) {
                if (!aw_event_queue_init(&events, event_descriptors, memory.blocks[3].address))
                    status = STATUS_DATA_ERROR;
                else {
                    /* Simulate one completed MCU event, never publish it to hardware. */
                    event_descriptors[0].control = 0xc0000000u | (36u << 16);
                    if (aw_event_queue_take(&events, &buffer, &length) != 1 || buffer != 0 || length != 36 ||
                        !aw_event_queue_repost(&events, buffer)) status = STATUS_DATA_ERROR;
                }
            }
        }
        if (NT_SUCCESS(status)) {
            result->size = sizeof(*result);
            result->version = AWDROP_DIAG_DMA_VERSION;
            result->allocated_bytes = AW_MCU_MEMORY_BYTES;
            result->address_bits = 32;
            result->alignment = 16;
        }
        /* All partial allocations are freed. No address is exposed or
         * programmed into the device, including during failure cleanup. */
        (void)aw_mcu_memory_release(&memory, &allocator, 0);
        WdfObjectDelete(enabler);
        WdfRequestCompleteWithInformation(request, status, NT_SUCCESS(status) ? sizeof(*result) : 0);
        return;
    }
    if (output_length < sizeof(*output)) {
        WdfRequestComplete(request, STATUS_BUFFER_TOO_SMALL);
        return;
    }
    status = WdfRequestRetrieveOutputBuffer(request, sizeof(*output), (PVOID *)&output, &actual);
    if (!NT_SUCCESS(status)) { WdfRequestComplete(request, status); return; }
    *output = ctx->info;
    WdfRequestCompleteWithInformation(request, STATUS_SUCCESS, sizeof(*output));
}
